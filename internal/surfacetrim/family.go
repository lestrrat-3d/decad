// Package surfacetrim holds the prism-family entry gate of Trim, Extend and
// Split, S1's sweep-family reading and S7's section-displacement reading over
// every payload shape, and Extend's free-end widening for both families
// (docs/surface-intersection-design.md §2.1, §2.2, §3.1). The root keeps the
// public entry points, the result builds and the commits. The revolve arm's
// S2-S7 live in internal/revolveplan for Trim and Extend, and in root
// surface_split_revolve.go for Split.
package surfacetrim

import (
	"github.com/lestrrat-3d/decad/internal/chainrecord"
	"github.com/lestrrat-3d/decad/internal/prismrecord"
	"github.com/lestrrat-3d/decad/internal/revolveplan"
	"github.com/lestrrat-3d/decad/internal/topo"
)

// Family is S1's own vocabulary: which one-parameter rigid motion a payload's
// sweep is generated by. Two payloads reduce to a common 2D section space only
// when they share one (docs/surface-intersection-design.md §1).
type Family uint8

const (
	FamilyUnknown Family = iota
	FamilyPrism
	FamilyRevolve
)

// String is what a refusal message names — the generator, never the payload
// class (T181): "a straight sweep" or "a revolve" reads the same whether the
// body came from Extrude or chain Extrude, Revolve or chain Revolve.
func (f Family) String() string {
	switch f {
	case FamilyPrism:
		return "a straight sweep"
	case FamilyRevolve:
		return "a revolve"
	default:
		return "an unrecognized sweep"
	}
}

// FamilyOf reads S1 off a body's own payload.
func FamilyOf(b *topo.Body) Family {
	switch b.Payload.(type) {
	case prismrecord.Payload, chainrecord.Payload:
		return FamilyPrism
	case revolveplan.Payload, revolveplan.ChainPayload:
		return FamilyRevolve
	default:
		return FamilyUnknown
	}
}

// RevolvePair reports whether S1 routes the pair to the revolve arm: both
// operands are revolve-family. A MIXED pair is not one; it falls through to the
// prism arm's gate, whose own S1 names the two generators that share nothing.
func RevolvePair(a, b *topo.Body) bool {
	return FamilyOf(a) == FamilyRevolve && FamilyOf(b) == FamilyRevolve
}

// SectionDelta reads S7's own section-displacement bound off a body,
// generically over all four shapes one may carry: a prism or revolve record's
// own SectionDelta, or a chain or chain-revolve record's identical field
// (docs/surface-intersection-design.md §3.4). Every caller reads it only after
// S1 has placed the body in one of the four, so the zero default is never read.
func SectionDelta(b *topo.Body) float64 {
	switch p := b.Payload.(type) {
	case prismrecord.Payload:
		return p.SectionDelta
	case chainrecord.Payload:
		return p.SectionDelta
	case revolveplan.Payload:
		return p.SectionDelta
	case revolveplan.ChainPayload:
		return p.SectionDelta
	default:
		return 0
	}
}
